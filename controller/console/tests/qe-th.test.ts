it.each([['ar', 'Transit defaults 副本'], ['en', 'Transit defaults (Copy)']])(
  'G-th W9 copy prefill focus selection blank disabled 409 persists %s', async (lang, expected) => {
    state.locale = lang as 'ar' | 'en'
    const { w, intercept } = await mountQE('/thresholds')
    const copy = lang === 'ar' ? '复制' : 'Copy'
    await clickText(w.findAll('tbody tr').find(r => r.text().includes('Transit defaults'))!, copy)
    const field = w.get('.inline input')
    expect(field.element).toBe(document.activeElement)
    expect((field.element as HTMLInputElement).selectionStart).toBe(0)
    expect((field.element as HTMLInputElement).selectionEnd).toBe(expected.length)
    expect((field.element as HTMLInputElement).value).toBe(expected)
    await field.setValue('  ')
    const button = w.findAll('.inline button').find(b => b.text() === copy)!
    expect(button.attributes('disabled')).toBeDefined()
    await button.trigger('click')
    expect(writes()).toHaveLength(0)
    await field.setValue('New copy')
    intercept((_p, i) => i.method === 'POST' ? response(409, { error: 'duplicate conflict' }) : undefined)
    await button.trigger('click'); await flushPromises()
    expect(body()).toEqual({ name: 'New copy' })
    expect(w.get('.inline [role=alert]').text()).toBe('duplicate conflict')
    expect(notifications.at(-1)).toMatchObject({ message: 'duplicate conflict', tone: 'crit' })
    intercept()
    await button.trigger('click'); await flushPromises()
    expect(w.find('.inline').exists()).toBe(false)
    expect(notifications.at(-1)?.message).toBe(lang === 'ar' ? '已复制' : 'Copied')
  })
