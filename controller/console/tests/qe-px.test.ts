it('G-px delete 500 raw stays then succeeds and reloads', async () => {
  const { w, intercept } = await mountQE('/prefixes', (_p, i) => i.method === 'DELETE'
    ? response(500, { error: 'delete failed' }) : undefined)
  await clickText(w.findAll('tbody tr')[0], '删除')
  await clickText(w.get('[role=alertdialog]'), '删除')
  expect(w.get('[role=alertdialog]').text()).toContain('delete failed')
  expect(notifications.at(-1)).toMatchObject({ message: 'delete failed', tone: 'crit' })
  intercept()
  await clickText(w.get('[role=alertdialog]'), '删除')
  expect(w.find('[role=alertdialog]').exists()).toBe(false)
  expect(calls('/api/prefixes')).toHaveLength(2)
  expect(notifications.at(-1)?.message).toBe('已删除')
})
