it('G-px W5 W6 mount three GET no polling nine columns disabled parent baseline states', async () => {
  clock()
  const { w } = await mountQE('/prefixes')
  expect(calls('/api/prefixes')).toHaveLength(1)
  expect(calls('/api/threshold-templates')).toHaveLength(1)
  expect(calls('/api/baseline')).toHaveLength(1)
  expect(w.findAll('th')).toHaveLength(9)
  expect(w.get('.disabled-row').text()).toContain('10.3.0.0/16')
  expect(w.get('[title="10.1.0.0/16 (Transit)"]').text()).toBe('1')
  expect(w.text()).toContain('P95 150')
  expect(w.text()).toContain('→ 300')
  expect(w.text()).toContain('⏳')
  expect(w.text()).toContain('最近 1 小时数据不足 60 个点，尚未给出推荐')
  expect(w.text()).not.toContain('/3600')
  await tick(60000)
  expect(calls('/api/prefixes')).toHaveLength(1)
  expect(calls('/api/threshold-templates')).toHaveLength(1)
  expect(calls('/api/baseline')).toHaveLength(1)
  await clickText(w.findAll('tbody tr').find(r => r.text().includes('10.1.0.0/16'))!, '删除')
  expect(w.get('[role=alertdialog]').text()).toContain('删除前缀 10.1.0.0/16？')
  expect(w.get('[role=alertdialog]').text())
    .toContain('该前缀的单独阈值规则会一并删除；它的子前缀会变成顶级前缀。')
})
it('G-px null empty and auxiliary failures silent preserve primary rows on retry failure', async () => {
  const { w, intercept } = await mountQE('/prefixes', (p, _i, r) => p.startsWith('/api/prefixes') ? undefined
    : response(503, { error: 'silent auxiliary' }))
  expect(w.find('[role=alert]').exists()).toBe(false)
  expect(w.text()).not.toContain('Transit defaults')
  expect(w.text()).not.toContain('P95')
  intercept(() => response(503, { error: 'prefix read failed' }))
  const page = w.findComponent({ name: 'Prefixes' })
  await (page.vm as any).$.setupState.refresh()
  await flushPromises()
  expect(w.get('[role=alert]').text()).toContain('prefix read failed')
  expect(w.text()).toContain('10.1.0.0/16')
  w.unmount()
  const empty = await mountQE('/prefixes', (p) => p.startsWith('/api/prefixes') ? response(200, null) : undefined)
  expect(empty.w.text()).toContain('暂无数据')
})
it('G-px create five keys blank disabled server 400 persists and retry reloads all three', async () => {
  const { w, intercept } = await mountQE('/prefixes')
  await clickText(w, '添加前缀')
  expect([...dialog().querySelectorAll('button')].find(b => b.textContent?.trim() === '创建')?.disabled).toBe(true)
  expect(dialog().querySelector('input')?.getAttribute('autocomplete')).toBe('off')
  await textInput('前缀 (CIDR)', ' 198.51.100.0/24 ')
  await textInput('名称', 'New prefix')
  await textInput('IP 分组', 'g')
  await choose('父级前缀', '10.1.0.0/16 (Transit)', dialog())
  await choose('阈值模板', 'Transit defaults', dialog())
  intercept((_p, i) => i.method === 'POST' ? response(400, { error: 'Use IPv4 notation for IPv4-mapped prefixes' })
    : undefined)
  await domClick('创建')
  expect(body()).toEqual({ prefix: '198.51.100.0/24', name: 'New prefix', ip_group: 'g', parent_id: 1,
    threshold_template_id: 7 })
  expect(dialog().querySelector('[role=alert]')?.textContent).toBe('Use IPv4 notation for IPv4-mapped prefixes')
  expect(notifications.at(-1)).toMatchObject({ tone: 'crit', message: 'Use IPv4 notation for IPv4-mapped prefixes' })
  intercept()
  await domClick('创建')
  expect(document.querySelector('[role=dialog]')).toBeNull()
  for (const path of ['/api/prefixes', '/api/threshold-templates', '/api/baseline']) {
    expect(calls(path).filter(([, i]) => !i?.method || i.method === 'GET')).toHaveLength(2)
  }
  expect(notifications.at(-1)?.message).toBe('前缀已创建')
})
